_cache_r, _cache_i = {}, {}

def _svg(name, color, fill):
    body = _P.get(name, _P["music"])
    f = color if fill else "none"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{f}" stroke="{color}" '
            f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')

def renderer(name, color="#ffffff", fill=False):
    key = (name, color, fill)
    if key not in _cache_r:
        _cache_r[key] = QSvgRenderer(QByteArray(_svg(name, color, fill).encode()))
    return _cache_r[key]

def draw(p: QPainter, name, rect: QRectF, color="#ffffff", fill=False, opacity=1.0):
    p.save()
    p.setOpacity(p.opacity() * opacity)
    renderer(name, color, fill).render(p, rect)
    p.restore()

def draw_play_pause(p, cx, cy, size, m, color="#ffffff"):
    """m = 0 mostra play, m = 1 mostra pause; entre os dois faz crossfade com escala"""
    for name, w in (("play", 1 - m), ("pause", m)):
        if w <= 0.01:
            continue
        isz = size * (0.55 + 0.45 * w)
        off = 1.5 * (1 - m) if name == "play" else 0.0  # o triângulo é opticamente centrado um pouco à direita
        draw(p, name, QRectF(cx - isz / 2 + off, cy - isz / 2, isz, isz), color, True, opacity=max(0.0, min(1.0, w)))

def pixmap(name, color="#ffffff", size=18, fill=False, dpr=2):
    pm = QPixmap(size * dpr, size * dpr)
    pm.fill(Qt.transparent)
    pm.setDevicePixelRatio(dpr)
    p = QPainter(pm)
    p.setRenderHint(QPainter.Antialiasing)
    renderer(name, color, fill).render(p, QRectF(0, 0, size, size))
    p.end()
    return pm

def icon(name, color="#ffffff", size=18, fill=False, selected_color=None):
    key = (name, color, size, fill, selected_color)
    if key not in _cache_i:
        ic = QIcon()
        ic.addPixmap(pixmap(name, color, size, fill), QIcon.Normal, QIcon.Off)
        if selected_color:
            ic.addPixmap(pixmap(name, selected_color, size, fill), QIcon.Selected, QIcon.Off)
        _cache_i[key] = ic
    return _cache_i[key]
